#!/usr/bin/env ruby
# frozen_string_literal: true

require "fileutils"

# Build www/app_bundle.rb: emulation stubs + ED2208 driver + assets + app.
# `require` lines are stripped from driver/app sources because the bundle
# already contains everything in one file.

ROOT = File.expand_path("..", __dir__) # emulator/

def strip_requires(src)
  src.split("\n").reject { |l| l =~ /^\s*require / }.join("\n")
end

parts = []

# 1) Emulation stubs (GPIO/SPI/I2C/VRAM/BDFFont/sleep_ms)
parts << <<~HEADER
  # ==== emulator stubs ====
HEADER
parts << File.read(File.join(ROOT, "src", "stubs.rb"))

# 2) ED2208 driver (same source as the gem)
parts << <<~HEADER
  # ==== picoruby-ed2208 driver ====
HEADER
parts << strip_requires(File.read(File.join(ROOT, "..", "picoruby", "picoruby-ed2208", "mrblib", "ed2208.rb")))

# 3) Terminus font data (pure-Ruby rendering)
parts << <<~HEADER
  # ==== terminus font data ====
HEADER
parts << File.read(File.join(ROOT, "www", "terminus_data.rb"))

# 3b) Wire the pure-Ruby drawables into the driver class
parts << <<~RUBY
  # ==== emulator wiring ====
  class ED2208
    include BDFFont::Drawable
    include Terminus::Drawable
  end
RUBY

# 4) Assets (generated by gen_assets.rb)
parts << <<~HEADER
  # ==== assets ====
HEADER
parts << File.read(File.join(ROOT, "www", "assets.rb"))

# 4) App
parts << <<~HEADER
  # ==== app ====
HEADER
parts << strip_requires(File.read(File.join(ROOT, "..", "picoruby", "app.rb")))

out = File.join(ROOT, "www", "app_bundle.rb")
File.write(out, parts.join("\n\n") + "\n")
puts "wrote #{out} (#{File.size(out)} bytes)"

# --- Device bundle: R2P2-ESP32 storage/home/app.rb ---
# On device the ED2208 driver comes from the gembox (picoruby-ed2208) and
# Terminus text rendering from picoruby-terminus, so only assets + app
# are concatenated. require lines are stripped (gems are built-in).
device_parts = []
device_parts << "# Generated by emulator/src/gen_bundle.rb -- device bundle"
device_parts << File.read(File.join(ROOT, "www", "assets.rb"))
device_parts << strip_requires(File.read(File.join(ROOT, "..", "picoruby", "app.rb")))

storage_home = File.join(ROOT, "..", "picoruby", "R2P2-ESP32", "storage", "home")
FileUtils.mkdir_p(storage_home)
device_out = File.join(storage_home, "app.rb")
File.write(device_out, device_parts.join("\n\n") + "\n")
puts "wrote #{device_out} (#{File.size(device_out)} bytes)"
