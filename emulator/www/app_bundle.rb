# Generated by emulator/gen_assets.rb -- do not edit manually.
# 1-bit bitmaps, horizontal packing, MSB = leftmost pixel.
# Stored as Base64 literals: byte-escaped literals would be invalid UTF-8.

def _decode_b64(s)
  table = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
  bytes = []
  i = 0
  n = s.size
  while i < n
    c0 = table.index(s[i])
    break if c0.nil?
    c1 = i + 1 < n ? table.index(s[i + 1]) : nil
    c2 = i + 2 < n ? table.index(s[i + 2]) : nil
    c3 = i + 3 < n ? table.index(s[i + 3]) : nil
    if c1 && c2 && c3
      bytes << ((c0 << 2) | (c1 >> 4))
      bytes << (((c1 & 0xF) << 4) | (c2 >> 2))
      bytes << (((c2 & 0x3) << 6) | c3)
      i += 4
    elsif c1 && c2
      bytes << ((c0 << 2) | (c1 >> 4))
      bytes << (((c1 & 0xF) << 4) | (c2 >> 2))
      i += 3
    elsif c1
      bytes << ((c0 << 2) | (c1 >> 4))
      i += 2
    else
      i += 1
    end
  end
  out = "\x00" * bytes.size
  j = 0
  while j < bytes.size
    out.setbyte(j, bytes[j])
    j += 1
  end
  out
end


