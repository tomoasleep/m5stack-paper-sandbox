#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate Terminus font data as pure-Ruby literals for the WASM emulator
# (and any environment without the C-backed picoruby-terminus gem).
# Output: www/terminus_data.rb containing TERMINUS_DATA.
#
# Format mirrors picoruby-bdffont's render contract:
#   glyph row = Integer, bit (w-1-x) set when pixel (x) is ink
#   (so row >> ... reads left-to-right, MSB = leftmost pixel)
# Only ASCII 0x20..0x7E, same as the C tables.

ROOT = File.expand_path("..", __dir__)
LIB = File.expand_path("picoruby/R2P2-ESP32/components/picoruby-esp32/picoruby/mrbgems/picoruby-terminus/lib/terminus-font-4.49.1", ROOT)
OUT = File.join(ROOT, "emulator", "www", "terminus_data.rb")

FONTS = [
  { name: "6x12",   file: "ter-u12n.bdf" },
  { name: "8x16",   file: "ter-u16n.bdf" },
  { name: "12x24",  file: "ter-u24n.bdf" },
  { name: "16x32",  file: "ter-u32n.bdf" },
]

RANGE = (0x20..0x7E).freeze

def parse_bdf_glyphs(path, w, h)
  glyphs = {}
  lines = File.readlines(path, chomp: true)
  i = 0
  while i < lines.size
    unless lines[i]&.start_with?("STARTCHAR")
      i += 1
      next
    end
    enc_line = lines[i + 1..].find { |l| l.start_with?("ENCODING") }
    code = enc_line.split[1].to_i
    bitmap_start = lines[i..].index { |l| l.strip == "BITMAP" } + i + 1
    row_bytes = (w + 7) / 8
    rows = []
    y = 0
    while y < h
      row_hex = lines[bitmap_start + y].strip
      need = (w + 7) / 4
      row_hex = row_hex.ljust(need, "0")[0, need]
      bits = row_hex.to_i(16).to_s(2).rjust(need * 4, "0")[0, w]
      row = 0
      x = 0
      while x < w
        row = (row << 1) | (bits[x] == "1" ? 1 : 0)
        x += 1
      end
      rows << row
      y += 1
    end
    glyphs[code] = rows
    i = lines[i..].index("ENDCHAR") + i + 1
  end
  glyphs
end

def ruby_rows(rows)
  "[" + rows.join(",") + "]"
end

entries = FONTS.map do |f|
  path = File.join(LIB, f[:file])
  raise "BDF not found: #{path}" unless File.exist?(path)
  w, h = f[:name].split("x").map(&:to_i)
  glyphs = parse_bdf_glyphs(path, w, h)
  puts "#{f[:name]}: #{glyphs.size} glyphs (#{w}x#{h})"
  body = RANGE.map do |cp|
    rows = glyphs[cp] || Array.new(h, 0)
    "    #{cp} => #{ruby_rows(rows)},"
  end.join("\n")
  "  \"#{f[:name]}\" => { w: #{w}, h: #{h}, glyphs: {\n#{body}\n  } },"
end.join("\n")

File.write(OUT, <<~RUBY)
  # Generated by emulator/gen_font.rb -- do not edit manually.
  # Terminus (regular) glyph bitmaps as Ruby integers, one per row,
  # bit (w-1-x) = pixel x. ASCII 0x20..0x7E only, like the C tables.

  TERMINUS_DATA = {
  #{entries}
  }
RUBY
puts "wrote #{OUT}"
